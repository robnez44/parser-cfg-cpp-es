"""How much the grammar grows when agreement is added (CONTRATO_FASE2.md, section 5).

es_base.gram has no agreement: 18 productions. es.gram has gender and number:
35 productions. This script measures the same growth on grammars built with
more agreement features, to see the trend and not only two points.

The grammars are built with the structure of es.gram. With ``features`` binary
features on the noun phrase (the first is number, the second gender, the rest
are hypothetical, like a third feature that also had to agree):

  - the noun phrase has k = 2**features classes (MS, FS, MP, FP for two features),
    and each class needs its own determiner, noun, adjective list and noun phrase;
  - subject and verb agree in number, so there are 2 groups (Sing and Plur).

Each grammar is read back with the verifier (the same code that checks es.gram),
so the counts are measured, not computed from the formula. The formula
``4k + 3n + 13`` for k classes and n number groups is checked against them.

    uv run python -m experiments.grammar_growth

prints the table and writes it to results/grammar_growth.md.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

from verifier.grammar import parse_grammar, read_grammar
from verifier.ll1 import analyze

ROOT = Path(__file__).resolve().parent.parent
GRAMMARS = ROOT / "grammars"
RESULTS = ROOT / "results"

# Productions that do not depend on the classes (Sentence, EndMark, NpTail, ...), as in es.gram.
SHARED = """\
Sentence -> Clause EndMark
EndMark -> PERIOD | ε
NpTail -> PrepPhrase NpTail | ε
PrepPhrase -> PREP NounPhrase
VpTail -> Object AdvOpt PpList
Object -> NounPhrase | ε
AdvOpt -> ADV | ε
PpList -> PrepPhrase PpList | ε
"""


@dataclass(frozen=True)
class Size:
    label: str
    features: int
    classes: int          # noun phrase classes (k)
    productions: int
    nonterminals: int
    terminals: int
    conflicts: int        # LL(1) conflicts that are not the accepted one


def build_agreement_grammar(features: int) -> str:
    """Text of a grammar with the structure of es.gram and 2**features noun phrase classes.

    Class ``c`` is a number from 0 to k-1. Its lowest bit is the number (0 singular,
    1 plural), so the classes with an even index are the singular ones.
    """
    if features < 1:
        raise ValueError("agreement needs at least one feature (number)")
    classes = 2**features
    lines = [
        "# Grammar for a Spanish subset with agreement (generated by experiments/grammar_growth.py)",
        "# Accepted LL(1) conflict: M[NpTail, PREP]",
        "",
        "Clause -> NpSing VpSing | NpPlur VpPlur",
        "NounPhrase -> NpSing | NpPlur",
        "NpSing -> " + " | ".join(f"Np{c}" for c in range(0, classes, 2)),
        "NpPlur -> " + " | ".join(f"Np{c}" for c in range(1, classes, 2)),
        "VpSing -> VERB_S VpTail",
        "VpPlur -> VERB_P VpTail",
    ]
    for c in range(classes):
        lines.append(f"Np{c} -> DET_{c} NOUN_{c} AdjList{c} NpTail")
        lines.append(f"AdjList{c} -> ADJ_{c} AdjList{c} | ε")
    return "\n".join(lines) + "\n" + SHARED


def measure(label: str, text: str, features: int, classes: int) -> Size:
    grammar = parse_grammar(text)
    analysis = analyze(grammar)
    return Size(
        label=label,
        features=features,
        classes=classes,
        productions=len(grammar.productions),
        nonterminals=len(grammar.nonterminals),
        terminals=len(grammar.terminals),
        conflicts=len(analysis.unaccepted_conflicts()),
    )


def expected_productions(classes: int, groups: int = 2) -> int:
    """Productions of the generated grammar: 4k + 3n + 13."""
    return 4 * classes + 3 * groups + 13


def growth_table(max_features: int = 5) -> list[Size]:
    """Sizes of es_base.gram (no agreement) and of the grammars with 1 to ``max_features`` features."""
    base_text = (GRAMMARS / "es_base.gram").read_text(encoding="utf-8")
    rows = [measure("Sin concordancia (`es_base.gram`)", base_text, 0, 1)]
    names = {1: "Número", 2: "Género y número (`es.gram`)"}
    for features in range(1, max_features + 1):
        label = names.get(features, f"{features} rasgos")
        rows.append(measure(label, build_agreement_grammar(features), features, 2**features))
    return rows


def format_table(rows: list[Size]) -> str:
    base = rows[0]
    lines = [
        "| Gramática | Rasgos | Clases de sintagma nominal | Producciones | No terminales | Terminales | Producciones respecto a `es_base.gram` |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row.label} | {row.features} | {row.classes} | {row.productions} | {row.nonterminals} | "
            f"{row.terminals} | ×{row.productions / base.productions:.1f} |"
        )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Tabla de crecimiento de la gramática por concordancia.")
    parser.add_argument("--features", type=int, default=5, help="máximo de rasgos de la tabla (por omisión, 5)")
    parser.add_argument("--no-write", action="store_true", help="no escribe results/grammar_growth.md")
    args = parser.parse_args(argv)

    rows = growth_table(args.features)
    table = format_table(rows)
    real = read_grammar(GRAMMARS / "es.gram")
    generated = next(row for row in rows if row.features == 2)
    same = (len(real.productions), len(real.nonterminals), len(real.terminals)) == (
        generated.productions,
        generated.nonterminals,
        generated.terminals,
    )
    print(table)
    print()
    print(f"La gramática generada con 2 rasgos tiene el mismo tamaño que es.gram: {'sí' if same else 'NO'}.")
    if any(row.conflicts for row in rows):
        print("ATENCIÓN: alguna gramática tiene conflictos sin aceptar.")
    else:
        print("Todas conservan el conflicto aceptado M[NpTail, PREP] y ninguno más.")
    if not args.no_write:
        RESULTS.mkdir(exist_ok=True)
        path = RESULTS / "grammar_growth.md"
        path.write_text(table + "\n", encoding="utf-8")
        print(f"Tabla escrita en {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
